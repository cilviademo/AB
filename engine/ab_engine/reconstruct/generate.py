def waveshaper_source(ws: dict[str, Any], params: list[dict[str, Any]]) -> str:
    fam = ws["family"]
    decl, expr = families.shape_body(fam, ws["params"])
    by_key = {p["key"]: p for p in params if p.get("generate")}
    lines = [HEADER, "#pragma once", "#include <cmath>", "#include <juce_audio_processors/juce_audio_processors.h>", "",
             f"// Waveshaper — BEHAVIOR_MATCHED {ws['rmse']:.3g} RMSE ({ws['classification_at_default']}) at the verified default,",
             f"// reference {ws['reference']} ({ws['curve_points']} points, x ∈ [{ws['x_range'][0]:.2f}, {ws['x_range'][1]:.2f}]).",
             f"// Family {fam}: {families.describe(fam)} — chosen by residual ({ws['family_basis']}).",
             "// Model: y = post · F (drive · pre · x). Parameter laws below were each measured one-at-a-time from the verified default;",
             "// their combination is INFERRED (separable). Statuses per law are in reconstruction_index.json.",
             "namespace ab_rebuild {", "struct Waveshaper", "{"]
    if decl:
        lines.append(decl.rstrip("\n"))
    lines += [f"    static constexpr float defaultDrive = {_f(ws['drive'])};",
              f"    static constexpr float defaultPost  = {_f(ws['post'])};",
              "    float pre = 1.0f, drive = defaultDrive, post = defaultPost;",
              "    bool passthrough = false, linear = false;",
              "    float linearSlope = 1.0f;", "",
              "    float process (float x) const noexcept",
              "    {",
              "        if (passthrough) return x;",
              "        if (linear) return linearSlope * x;",
              "        const float u = drive * pre * x;",
              "        juce::ignoreUnused (u);",
              f"        return post * ({expr});",
              "    }", "",
              "    // Per-block parameter application (the original smooths gains over ~20 ms — measured settle; INFERRED, not modelled).",
              "    void update (const juce::AudioProcessorValueTreeState& apvts) noexcept",
              "    {",
              "        pre = 1.0f; drive = defaultDrive; post = defaultPost; passthrough = false; linear = false; linearSlope = 1.0f;"]
    for mo in ws["modulation"]:
        p = by_key.get(mo["key"])
        if p is None:
            continue
        key = _cpp_str(mo["key"])
        law, knob = mo["law"], mo["knob"]
        tag = f"// {mo['status']} — {mo['law']}: {mo['basis']}"
        if law in ("none", "unmodeled"):
            lines.append(f"        // {mo['key']}: {tag[3:]}")
            continue
        lines.append(f"        {tag}")
        if law == "db":
            lines.append(f"        {knob} *= juce::Decibels::decibelsToGain (apvts.getRawParameterValue ({key})->load() - {_f(p['default'])});")
        elif law == "proportional":
            lines.append(f"        {knob} *= apvts.getRawParameterValue ({key})->load() / {_f(p['default'])};")
        elif law == "passthrough":
            lines.append(f"        if (apvts.getRawParameterValue ({key})->load() >= 0.5f) passthrough = true;")
        elif law == "passthrough_off":
            lines.append(f"        if (apvts.getRawParameterValue ({key})->load() < 0.5f) passthrough = true;")
        elif law == "discrete":
            var = f"v_{_ident(mo['key'])}"
            lines.append(f"        const int {var} = (int) std::lround (apvts.getRawParameterValue ({key})->load());")
            for r in mo["points"]:
                v = int(r.get("value", 0))
                if r.get("passthrough"):
                    lines.append(f"        if ({var} == {v}) passthrough = true;  // measured: identity")
                elif r.get("is_linear"):
                    lines.append(f"        if ({var} == {v}) {{ linear = true; linearSlope = {_f(r['linear']['slope'])}; }}  // measured: linear, RMSE {r['linear']['rmse']:.1e}")
                elif r["knob"] in ("pre", "drive", "post") and abs(r["factor"] - 1) > 5e-3:
                    lines.append(f"        if ({var} == {v}) {r['knob']} *= {_f(r['factor'])};  // measured factor, RMSE {r['rmse']:.1e}")
                else:
                    lines.append(f"        // {var} == {v}: default (no change measured)")
        elif law == "table":
            xs = ", ".join(_f(r["normalized"]) for r in mo["points"])
            fs = ", ".join(_f(r["factor"]) for r in mo["points"])
            ks = {r["knob"] for r in mo["points"] if r["knob"] in ("pre", "drive", "post")}
            k = next(iter(ks)) if len(ks) == 1 else "pre"
            lines.append(f"        {{ static const float xs[] = {{ {xs} }}; static const float fs[] = {{ {fs} }};")
            lines.append(f"          {k} *= interp (apvts.getParameter ({key})->getValue(), xs, fs, {len(mo['points'])}); }}  // INFERRED between the measured positions")
    lines += ["    }", "",
              "    static float interp (float n, const float* xs, const float* fs, int count) noexcept",
              "    {",
              "        if (count <= 0) return 1.0f;",
              "        if (n <= xs[0]) return fs[0];",
              "        for (int i = 1; i < count; ++i)",
              "            if (n <= xs[i]) { const float t = (n - xs[i - 1]) / (xs[i] - xs[i - 1]); return fs[i - 1] + t * (fs[i] - fs[i - 1]); }",
              "        return fs[count - 1];",
              "    }",
              "};", "} // namespace ab_rebuild", ""]
    return "\n".join(lines)


