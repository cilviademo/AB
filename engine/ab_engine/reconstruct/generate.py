def parameters_source(params: list[dict[str, Any]], state: dict[str, Any]) -> str:
    lines = [HEADER, "#pragma once", "#include <juce_audio_processors/juce_audio_processors.h>", "",
             "// Parameter layout — every row is a VST3_EXPORTED_PARAMETER seen by vst3host (VERIFIED_RUNTIME); ids reproduce the",
             "// original VST3 ParamIDs through juce::ParameterID{key, 1} (JUCE hashCode rule) where id_status says so.",
             "namespace ab_rebuild {",
             f"static constexpr const char* stateRootTag = {_cpp_str(state['root_tag'])};  // {state['root_status']}", "",
             "inline juce::AudioProcessorValueTreeState::ParameterLayout createParameterLayout()", "{",
             "    juce::AudioProcessorValueTreeState::ParameterLayout layout;"]
    for p in params:
        if not p.get("generate"):
            lines.append(f"    // {p.get('title')}: {p.get('note')}")
            continue
        pid = f"juce::ParameterID {{ {_cpp_str(p['key'])}, 1 }}"
        title = _cpp_str(p["title"])
        note = f"// {p['id_status']}"
        if p["kind"] == "bool":
            lines.append(f"    layout.add (std::make_unique<juce::AudioParameterBool> ({pid}, {title}, {'true' if p['default'] else 'false'}));  {note}; default VERIFIED_RUNTIME")
        elif p["kind"] == "choice":
            names = ", ".join(_cpp_str(c["name"]) for c in p["choices"])
            gen = [c["name"] for c in p["choices"] if c["status"].startswith("GENERATED")]
            lines.append(f"    layout.add (std::make_unique<juce::AudioParameterChoice> ({pid}, {title}, juce::StringArray {{ {names} }}, {p['default']}));  {note}; choice names {'VERIFIED_RUNTIME' if not gen else 'partly GENERATED: ' + ', '.join(gen)}")
        else:
            rng = f"juce::NormalisableRange<float> ({_f(p['min'])}, {_f(p['max'])}, 0.0f, {_f(p['skew'])})"
            attrs = f".withLabel ({_cpp_str(p['units'])})" if p.get("units") else ""
            lines.append(f"    layout.add (std::make_unique<juce::AudioParameterFloat> ({pid}, {title}, {rng}, {_f(p['default'])}, juce::AudioParameterFloatAttributes(){attrs}));  {note}; range {p['range_status']}")
    lines += ["    return layout;", "}", "} // namespace ab_rebuild", ""]
    return "\n".join(lines)


