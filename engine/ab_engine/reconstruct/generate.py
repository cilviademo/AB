HEADER = "// GENERATED by AB — Artifact Bench (reconstruction stage). Provenance: 07_agent_handoff/reconstruction_index.json\n"


def _f(v: float) -> str:
    return families._f(v)


def _ident(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return s if s and not s[0].isdigit() else f"P{s}"


def _cpp_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def surrogate_codes(product: str) -> tuple[str, str]:
    h = hashlib.sha256(product.encode("utf-8")).hexdigest()
    letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    return "AbSr", "S" + "".join(letters[int(h[i * 2:i * 2 + 2], 16) % len(letters)] for i in range(3))


