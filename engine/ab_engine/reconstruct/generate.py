"""Source generation for 04_reconstruction (SPEC §10, EXECUTE 4.2).

Writes, from the evidence model (``reconstruct.model``):

* ``human_source/``            concise idiomatic JUCE/C++ per module, evidence tags in comments
* ``evidence_source/``         decompiler pseudo-C for the DSP-role classes (copied from 01_evidence)
* ``Source/Active/``           ONLY what passed its gate: parameter layout (VERIFIED_RUNTIME ids),
                               processor/editor shell, and modules at ≥ BEHAVIORALLY_EQUIVALENT
* ``Source/RecoveredScaffolds/`` left as the static stage wrote them (not compiled)
* ``CMakeLists.txt``           FIDELITY | SURROGATE selected by the identity evidence
* ``07_agent_handoff/reconstruction_index.json``  statement-level provenance (symbol, file,
                               status, addresses, evidence, parameters, validation, rmse, todos)

Every generated value that is not VERIFIED or BEHAVIOR_MATCHED is tagged INFERRED or GENERATED
in the source and in the index. Nothing here bypasses or reimplements a PROTECTED_SUBSYSTEM.
"""

